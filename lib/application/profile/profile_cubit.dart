import '../../domain/common/exceptions.dart';

class ProfileState extends Equatable {
  const ProfileState({
    this.user,
    this.uploadPercent,
    this.uploadedImage,
    this.errorMessage,
    this.errorId = 0,
  });

  final LocalUser? user;

  /// Upload progress (0-100) while a new photo uploads, else `null`.
  final int? uploadPercent;

  /// Photo picked in this session, shown once its upload completed.
  final ImageData? uploadedImage;

  final String? errorMessage;
  final int errorId;

  bool get isUploading => uploadPercent != null;

  @override
  List<Object?> get props =>
      [user, uploadPercent, uploadedImage, errorMessage, errorId];
}

class ProfileCubit extends Cubit<ProfileState> {
  ProfileCubit(this._repository, this._session)
      : super(ProfileState(user: _session.currentUser)) {
    _sessionSub = _session.changes.listen((user) {
      if (!isClosed) {
        emit(ProfileState(
          user: user,
          uploadPercent: state.uploadPercent,
          uploadedImage: state.uploadedImage,
          errorId: state.errorId,
        ));
      }
    });
  }

  final IUserProfileRepository _repository;
  final ISession _session;
  late final StreamSubscription<LocalUser?> _sessionSub;
  StreamSubscription<UploadProgress>? _progressSub;

  void _emit({int? Function()? percent, ImageData? image, String? error}) {
    if (isClosed) return;
    emit(ProfileState(
      user: _session.currentUser,
      uploadPercent: percent != null ? percent() : state.uploadPercent,
      uploadedImage: image ?? state.uploadedImage,
      errorMessage: error,
      errorId: error != null ? state.errorId + 1 : state.errorId,
    ));
  }

  /// Uploads a new profile photo and points the profile at it. The 200x200
  /// thumbnail is generated by a storage extension.
  Future<void> uploadPhoto(ImageData image) async {
    try {
      final handle = _repository.uploadProfilePhoto(image);
      _emit(percent: () => 0);
      await _progressSub?.cancel();
      _progressSub = handle.progress.listen(
        (p) => _emit(percent: () => p.percent),
        onError: reportError,
      );
      final location = await handle.location;
      await _repository.setProfilePhoto(
        profilePhoto: location,
        thumbnail: profileThumbnailLocation(location),
      );
      await _repository.refreshCurrentUser();
      await _progressSub?.cancel();
      _emit(percent: () => null, image: image);
    } catch (e, stackTrace) {
      reportError(e, stackTrace);
      await _progressSub?.cancel();
      _emit(percent: () => null, error: 'Error uploading photo');
    }
  }

  @override
  Future<void> close() async {
    await _sessionSub.cancel();
    await _progressSub?.cancel();
    return super.close();
  }
}
