/// A completion is on time when made on (UTC) the content's day or earlier.
bool isOnTime(DateTime contentDate, DateTime now) {
  final n = now.toUtc();
  final d = contentDate.toUtc();
  if (d.year == n.year && d.month == n.month && d.day == n.day) return true;
  return d.isAfter(n);
}

/// Whether every question of [content] has a non-empty answer.
bool isResponsesFilled(Responses responses, SeriesContent content) {
  for (var i = 0; i < content.body.length; i++) {
    final body = content.body[i];
    if (body is! QuestionBody) continue;
    for (var j = 0; j < body.questions.length; j++) {
      final answer = responses.responses['$i']?['$j'];
      if (answer == null || answer.response == '') return false;
    }
  }
  return true;
}

/// Whether no response contains any text/location.
bool isResponseEmpty(Responses responses) {
  for (final body in responses.responses.values) {
    for (final answer in body.values) {
      if (answer.response.isNotEmpty) return false;
    }
  }
  return true;
}

/// `gs://…/responses/<uid>/<name>.<ext>` ->
/// `gs://…/responses/<uid>/thumbs/<name>_200x200.<ext>` (generated by the
/// image resize extension).
String responseThumbnailLocation(String location, String userId) {
  final parts = location.split(userId);
  final rest = parts[1];
  final dot = rest.lastIndexOf('.');
  final name = rest.substring(0, dot);
  final ext = rest.substring(dot);
  return '${parts[0]}$userId/thumbs${name}_200x200$ext';
}
